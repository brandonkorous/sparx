#!/usr/bin/env node
// `@sparx/*` → `@wizeworks/*`, for the packages that are the PLATFORM's.
//
// The scope is a historical accident: sparx was the only product when these were
// written, so the shared floor took its name. Thirty-odd of them are brand-blind
// platform code — a Prisma client, a query wrapper, a schema set — and a package
// Piggles cannot boot without, wearing another brand's name, is not something you
// can point at and call independent. See piggles/docs/migration/ (A3).
//
// ── THE MAP COMES FROM THE MANIFESTS, NOT FROM A REGEX ──────────────────────
//
// A blanket `s/@sparx\//@wizeworks\//` would be wrong in three ways at once,
// and the third is the one that matters:
//
//   1. It renames FRAGMENTS. `@sparx/provider-`, `@sparx/cms-`, `@sparx/x` all
//      appear in prose and none of them is a package.
//   2. It renames the ONES THAT STAY. `@sparx/brand` is sparx's marks, mascot
//      and token values; `@sparx/web`, `@sparx/market` and `@sparx/workbench`
//      are its applications. All four keep the scope and live under `sparx/`.
//      (`ui` was on this list until the tree move proved it brand-blind apart
//      from four re-exported marks — it is `@wizeworks/ui` now.)
//   3. It renames packages THAT DO NOT EXIST. About thirty tokens — `@sparx/ai`,
//      `@sparx/audit`, `@sparx/errors`, `@sparx/geo`, `@sparx/dashboard` — are
//      referenced only in docs. Some are planned, some name code that was
//      deleted. Renaming them would launder a stale reference into one that
//      looks current, which is strictly worse than leaving it obviously old.
//      They are REPORTED instead, so somebody can decide which is which.
//
// So the rename map is built by reading every workspace manifest. If a token is
// not a real package, it is left exactly as it was.
//
// ── ONE PASS, NOT WAVES ─────────────────────────────────────────────────────
//
// The plan filed this as three waves with `pnpm install && pnpm typecheck`
// between them. That works when you can install between waves; it does not
// otherwise, because the moment a package is renamed nothing resolves until the
// workspace is relinked. Half-renamed is the one state that is worse than either
// end. So: one atomic pass, then one install.
//
// Pure Node, no dependencies. `--write` to apply; default is a dry run.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const OLD_SCOPE = '@sparx';
const NEW_SCOPE = '@wizeworks';

/**
 * The four that keep the scope, because they genuinely belong to sparx.
 *
 * `brand` is its marks, mascot and token VALUES; the other three are its
 * applications. They live under `sparx/`, so the scope name and the directory
 * finally agree.
 */
const KEEP = new Set(['brand', 'web', 'market', 'workbench']);

const WORKSPACE_GLOBS = [
  'wizeworks/packages',
  'wizeworks/services',
  'wizeworks/apps',
  'sparx/packages',
  'sparx/apps',
  'piggles/apps',
  'piggles/packages',
];

const SKIP_DIRS = new Set([
  'node_modules',
  '.next',
  '.turbo',
  'dist',
  '.git',
  'coverage',
  'build',
  '.vercel',
]);

/**
 * Files whose `@sparx/` strings are DATA ABOUT the old scope, not references to
 * it — rewriting them destroys their meaning.
 *
 * `pnpm-lock.yaml` is regenerated by install; rewriting it by hand invites a
 * corrupt lock. The usage baseline is `check-boundaries`' ratchet, keyed by the
 * scope it counts — renaming its keys would leave every count unmatched and the
 * ratchet silently green. Regenerate it AFTER the rename instead
 * (`node scripts/check-boundaries.mjs --update-baseline`), where the new near-zero
 * numbers are the honest ones.
 */
const SKIP_FILES = new Set(['pnpm-lock.yaml', 'sparx-usage-baseline.json']);

const TEXT_EXT = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.json',
  '.jsonc',
  '.css',
  '.scss',
  '.md',
  '.mdx',
  '.yaml',
  '.yml',
  '.env',
  '.example',
  '.sh',
  '.txt',
  '.html',
  // Both hold only COMMENTS naming the package that owns a model or a resource,
  // and a comment that names a package which no longer exists is worse than no
  // comment. Neither file's behaviour depends on the string.
  '.prisma',
  '.tf',
]);

/**
 * `.sql` is ABSENT and must stay absent.
 *
 * Prisma checksums every applied migration and stores the hash in
 * `_prisma_migrations` on each deployed database. Editing one — even a comment,
 * even whitespace — makes `migrate deploy` refuse the whole release with a
 * checksum mismatch, on every environment at once, and the only remedy is
 * hand-editing production rows.
 *
 * Migrations are history. They are allowed to name things by the names those
 * things had at the time.
 */
const NEVER_REWRITE_DIRS = ['wizeworks/packages/db/prisma/migrations'];

/** Extensionless files that are still text we must rewrite. */
const TEXT_NAMES = new Set([
  'Dockerfile',
  '.npmrc',
  '.prettierignore',
  '.gitignore',
  '.dockerignore',
]);

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

function isTextFile(name) {
  if (TEXT_NAMES.has(name)) return true;
  if (name.startsWith('Dockerfile')) return true; // Dockerfile.base, Dockerfile.dev
  if (name.startsWith('.env')) return true;
  return TEXT_EXT.has(path.extname(name));
}

/**
 * Every SHORT NAME that is a real workspace package and is not one of the five
 * sparx keeps.
 *
 * Keyed on the short name and built from BOTH scopes on purpose, so the script
 * is idempotent and re-runnable. Keying it on `@sparx/*` manifests alone worked
 * exactly once: the moment the manifests were rewritten the map came back empty
 * and a second pass — for the file types the first pass had missed — refused to
 * run, with a message saying the rename was already done. It was not.
 *
 * A codemod that can only be run once is a codemod you cannot finish.
 */
function buildRenameMap() {
  const map = new Map();
  const kept = [];
  for (const glob of WORKSPACE_GLOBS) {
    const base = path.join(ROOT, glob);
    if (!fs.existsSync(base)) continue;
    for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const manifest = path.join(base, entry.name, 'package.json');
      if (!fs.existsSync(manifest)) continue;
      let name;
      try {
        name = JSON.parse(fs.readFileSync(manifest, 'utf8')).name;
      } catch {
        continue;
      }
      if (typeof name !== 'string') continue;
      const scope = name.startsWith(`${OLD_SCOPE}/`)
        ? OLD_SCOPE
        : name.startsWith(`${NEW_SCOPE}/`)
          ? NEW_SCOPE
          : null;
      if (!scope) continue;
      const short = name.slice(scope.length + 1);
      if (KEEP.has(short)) {
        kept.push(`${OLD_SCOPE}/${short}`);
        continue;
      }
      map.set(short, `${NEW_SCOPE}/${short}`);
    }
  }
  return { map, kept: kept.sort() };
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (NEVER_REWRITE_DIRS.includes(rel(full))) continue;
      walk(full, out);
    } else if (!SKIP_FILES.has(entry.name) && isTextFile(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

/**
 * One regex with a lookup, rather than N string replacements.
 *
 * The capture stops at the first character that cannot be part of a package
 * name, so the short name `cms` is never matched inside `cms-editor`, and a
 * subpath (`.../links/server`) keeps its subpath. A token that is not in the map
 * comes back unchanged, which is how the five kept packages and the thirty
 * phantom ones survive untouched.
 *
 * Note this script rewrote its OWN prose on the first run — every example here
 * used to spell the old scope out. Worth knowing before writing a codemod that
 * walks the whole tree: it will find itself.
 */
const TOKEN = /@sparx\/([a-zA-Z0-9-]+)/g;

function rewrite(text, map, unknown) {
  let changed = 0;
  const out = text.replace(TOKEN, (whole, short) => {
    const replacement = map.get(short);
    if (!replacement) {
      unknown.set(short, (unknown.get(short) ?? 0) + 1);
      return whole;
    }
    changed++;
    return replacement;
  });
  return { out, changed };
}

function main() {
  const write = process.argv.includes('--write');
  const { map, kept } = buildRenameMap();

  if (map.size === 0) {
    console.error('✗ no renamable packages found — refusing to run.');
    console.error('  Either the rename is already done, or WORKSPACE_GLOBS is wrong.\n');
    return 1;
  }

  const files = walk(ROOT);
  const unknown = new Map();
  const touched = [];
  let total = 0;

  for (const file of files) {
    let text;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    if (!text.includes(`${OLD_SCOPE}/`)) continue;
    const { out, changed } = rewrite(text, map, unknown);
    if (changed === 0) continue;
    total += changed;
    touched.push({ file: rel(file), changed });
    if (write) fs.writeFileSync(file, out);
  }

  const verb = write ? 'rewrote' : 'would rewrite';
  console.log(`${verb} ${total} reference(s) across ${touched.length} file(s)`);
  console.log(`  ${map.size} package(s) renamed, ${kept.length} kept: ${kept.join(', ')}\n`);

  const top = [...touched].sort((a, b) => b.changed - a.changed).slice(0, 15);
  console.log('  Heaviest files:');
  for (const t of top) console.log(`    ${String(t.changed).padStart(4)}  ${t.file}`);

  // Two very different reasons a token was left alone, and reporting them as one
  // list is how "@wizeworks/ui, 454 occurrences" reads like an oversight instead of
  // the deliberate decision it is.
  const keptShort = new Set([...KEEP]);
  const keptHits = [...unknown.entries()].filter(([n]) => keptShort.has(n));
  const phantoms = [...unknown.entries()].filter(([n]) => !keptShort.has(n));

  if (keptHits.length > 0) {
    const sorted = keptHits.sort((a, b) => b[1] - a[1]);
    console.log('\n  Kept deliberately — these belong to sparx and move to `sparx/` in A4:');
    for (const [name, count] of sorted) {
      console.log(`    ${String(count).padStart(4)}  ${OLD_SCOPE}/${name}`);
    }
  }

  if (phantoms.length > 0) {
    // Not a failure. These name packages that do not exist — planned, renamed or
    // deleted — and they were already stale before this ran. Left alone ON
    // PURPOSE: a phantom that still says `@sparx/` is visibly old, and one
    // silently promoted to `@wizeworks/` looks current and is not.
    const sorted = phantoms.sort((a, b) => b[1] - a[1]);
    console.log(`\n  ${sorted.length} token(s) name no workspace package — left as-is:`);
    for (const [name, count] of sorted) {
      console.log(`    ${String(count).padStart(4)}  ${OLD_SCOPE}/${name}`);
    }
    console.log('\n  Each is a doc reference to something planned, renamed or deleted,');
    console.log('  or a fragment of prose. Worth a pass; a rename is not the tool for it.');
  }

  if (!write) {
    console.log('\n  Dry run. Re-run with --write to apply, then `pnpm install`.');
  } else {
    console.log('\n  Applied. `pnpm install` now, before anything is expected to typecheck.');
  }
  return 0;
}

process.exit(main());
