/** The owner-facing title for a tool, or null when the tool has none. */
export function toolTitle(name: string): string | null {
  // hasOwn, so a name like "toString" never answers with Object's prototype.
  if (!Object.hasOwn(TOOL_TITLES, name)) return null;
  return TOOL_TITLES[name] ?? null;
}
