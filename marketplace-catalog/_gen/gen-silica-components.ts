// Generator: the marketplace COMPONENT shelf — one bundle per sparx silica section
// (`SPARX_CATALOG`, packages/silica-catalog). A marketplace component is a DISCOVERY
// listing for a section that already lives in the Site Builder's Insert palette: the
// payload is the section's silica node tree (`item.make()`), and "Start with this
// component" hands the slug to onboarding so the Builder inserts it via the existing
// path (docs/118). This replaces the retired legacy `BuilderNode` component bundles —
// one component system, surfaced publicly.
//
// Previews are LIVE (docs/118): the marketplace renders each section in-browser from
// its tree on the platform's base theme (apps/web `ComponentPreview`), so a bundle
// ships NO baked image — just sparx.json + component.ts.
//
// All listing copy is DERIVED from the catalog itself — the section's `label` is the
// name, its `hint` is the tagline, its group is the browse facet. The `hint` fields
// are already written for a non-technical business owner (the Builder palette shows
// them), so they carry over verbatim. Only the group→facet-label map below is authored.
//
// Run (docs marketplace-catalog/CLAUDE.md — the generator is the source of truth):
//   pnpm --filter @sparx/api-rest exec tsx "$PWD/marketplace-catalog/_gen/gen-silica-components.ts"
//   pnpm exec prettier --write "marketplace-catalog/components/**" "marketplace-catalog/_gen/gen-silica-components.ts"
//   pnpm --filter @sparx/api-rest marketplace:ingest
//
// WHY RELATIVE IMPORTS. This file reads the section catalog (a workspace package) but
// lives under marketplace-catalog/ which has no node_modules, so a bare `@sparx/*`
// specifier can't resolve here. Importing the package `src` by relative path lets tsx
// compile it in place. The EMITTED component.ts is the opposite discipline — pure data,
// no imports (the ingest resolves it with no workspace resolution).

import { promises as fs } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SPARX_CATALOG } from '../../packages/silica-catalog/src/catalog';
import type { CatalogGroup, CatalogItem } from '../../packages/silica-catalog/src/types';

const here = dirname(fileURLToPath(import.meta.url));
const catalog = join(here, '..'); // marketplace-catalog/
const componentsDir = join(catalog, 'components');

// ── The one authored table: a short, human "Purpose" facet per catalog group ──────
// The catalog group LABELS ("Helping people choose") exceed the DB `group` column's
// 20-char cap and read long as a filter chip, so each group gets a concise facet
// label here. This is the browse rail's "Purpose" dimension.
const GROUP_FACET: Record<string, string> = {
  commerce: 'Products',
  sparx_layout: 'Page structure',
  sparx_gallery: 'Pictures',
  sparx_compare: 'Comparison',
  sparx_process: 'How it works',
  sparx_people: 'People & proof',
  sparx_place: 'Where & when',
  sparx_convert: 'Get in touch',
  sparx_content: 'Writing',
  sparx_offer: 'Selling',
};

/** Section key → kebab-case marketplace slug (`product_card` → `product-card`). */
const toSlug = (key: string): string => key.replace(/_/g, '-');

const json = (value: unknown): string => JSON.stringify(value, null, 2) + '\n';

/** The emitted, pure-data component.ts payload — the section's silica node tree.
 *  The ingest `import()`s this module with no workspace resolution, so it carries
 *  ZERO imports: just `export default { tree: { … } }`. */
function componentTs(item: CatalogItem, group: CatalogGroup): string {
  const tree = item.make();
  return (
    `// sparx marketplace component — '${item.label}' (${GROUP_FACET[group.key]}). The silica\n` +
    `// section this listing surfaces: the exact node tree the Builder inserts from its\n` +
    `// Insert palette. GENERATED by marketplace-catalog/_gen/gen-silica-components.ts from\n` +
    `// SPARX_CATALOG — do NOT hand-edit. Pure data (no imports): the ingest resolves this\n` +
    `// module with no workspace resolution.\n` +
    `export default { tree: ${JSON.stringify(tree, null, 2)} } as const;\n`
  );
}

function sparxJson(opts: {
  slug: string;
  item: CatalogItem;
  group: CatalogGroup;
  sortWeight: number;
}): string {
  const { slug, item, group, sortWeight } = opts;
  return json({
    schemaVersion: 1,
    category: 'component',
    slug,
    name: item.label,
    version: '1.0.0',
    // The palette hint is already owner-facing copy — reuse it as the tagline; leave
    // the long description empty so the detail page shows the one line, not it twice.
    tagline: item.hint ?? item.label,
    description: '',
    payload: 'component.ts',
    facets: {
      group: GROUP_FACET[group.key],
      kind: 'Section',
      surfaces: ['page'],
    },
    pricing: { model: 'free', priceCents: 0 },
    // No media: components render a LIVE preview in-browser (docs/118), so a bundle
    // ships no baked image — the marketplace draws it from component.ts.
    media: [],
    author: { displayName: 'sparx' },
    sortWeight,
  });
}

async function main(): Promise<void> {
  await fs.mkdir(componentsDir, { recursive: true });
  // Flatten in catalog order so the browse order mirrors the palette; a descending
  // sortWeight keeps that order without depending on any per-item field.
  const flat: { item: CatalogItem; group: CatalogGroup }[] = [];
  for (const group of SPARX_CATALOG) {
    if (!GROUP_FACET[group.key]) {
      throw new Error(`gen-silica-components: no facet label for catalog group '${group.key}'`);
    }
    for (const item of group.items) flat.push({ item, group });
  }

  let written = 0;
  const total = flat.length;
  for (const [i, { item, group }] of flat.entries()) {
    const slug = toSlug(item.key);
    const bundleDir = join(componentsDir, slug);
    await fs.mkdir(bundleDir, { recursive: true });
    await fs.writeFile(
      join(bundleDir, 'sparx.json'),
      sparxJson({ slug, item, group, sortWeight: total - i })
    );
    await fs.writeFile(join(bundleDir, 'component.ts'), componentTs(item, group));
    written += 1;
    console.log(`  wrote components/${slug} (${GROUP_FACET[group.key]})`);
  }
  console.log(
    `\ngen-silica-components: ${written} component bundles written to ${componentsDir} (live preview, no media).`
  );
}

main().catch((err: unknown) => {
  console.error('gen-silica-components failed:', err);
  process.exit(1);
});
